// Package color provides commands for managing iTerm2 colors and appearance.
//
// This package includes:
//   - Color preset management (list, apply, import, export, create, delete)
//   - Future color-related functionality
//
// Commands:
//   - color preset list - List available color presets
//   - color preset apply <name> [profile] - Apply a color preset
//   - color preset import <name> <file> - Import from .itermcolors file
//   - color preset export <name> <file> - Export to .itermcolors file
//   - color preset create <name> [profile] - Create preset from profile
//   - color preset delete <name> - Delete a color preset
package color
