// Package prompt provides commands for managing prompts and command history
// in iTerm2 sessions using Shell Integration features.
//
// The prompt package includes subcommands for:
//   - list: List historical prompts in a session
//   - get: Get detailed information about a specific prompt
//   - monitor: Monitor prompt events in real-time
//   - search: Search through command history with pattern matching
//
// All commands require Shell Integration to be enabled in iTerm2.
package prompt